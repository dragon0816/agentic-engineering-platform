from pathlib import Path
import csv
import hashlib
import shutil

workspace = Path.cwd()
input_dir = workspace / 'input' / 'files'
output_root = workspace / 'output'
classified_root = output_root / 'classified'
manifest_path = output_root / 'manifest.csv'

if not input_dir.exists():
    raise FileNotFoundError(f'Missing input directory: {input_dir}')

categories = {
    '.pdf': 'PDF',
    '.xls': 'Excel',
    '.xlsx': 'Excel',
    '.png': 'Image',
    '.jpg': 'Image',
    '.jpeg': 'Image',
}

def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open('rb') as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()

# Clean only outputs generated by this task so reruns are deterministic; never touch input.
if classified_root.exists():
    shutil.rmtree(classified_root)
if manifest_path.exists():
    manifest_path.unlink()

rows = []
files = sorted((p for p in input_dir.rglob('*') if p.is_file()), key=lambda p: p.relative_to(input_dir).as_posix().lower())
for src in files:
    rel_under_files = src.relative_to(input_dir)
    category = categories.get(src.suffix.lower(), 'Other')
    dst = classified_root / category / rel_under_files
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)
    rows.append({
        '原路徑': src.relative_to(workspace).as_posix(),
        '新路徑': dst.relative_to(workspace).as_posix(),
        'SHA-256': sha256_file(src),
    })

output_root.mkdir(parents=True, exist_ok=True)
with manifest_path.open('w', newline='', encoding='utf-8-sig') as f:
    writer = csv.DictWriter(f, fieldnames=['原路徑', '新路徑', 'SHA-256'])
    writer.writeheader()
    writer.writerows(rows)

print('copied_files:', len(rows))
print('manifest:', manifest_path)
for row in rows:
    print(row['原路徑'], '->', row['新路徑'], row['SHA-256'])
