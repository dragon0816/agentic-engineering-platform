def trend_links(c: dict[str, list[Card]], d: str) -> dict[str, Any]:
    ecos, cps = _of(c, "Ecosystem", d), _of(c, "CustomerProduct", d)
    rows: list[list[Any]] = []
    flags: list[dict[str, Any]] = []
    for trend in sorted(_of(c, "Trend", d), key=lambda t: -_prio(t)):
        nodes = {str(n) for n in _list(trend.get("affected_nodes"))}
        techs = {str(t) for t in _list(trend.get("related_tech"))}
        by_tech = [e for e in ecos if techs & {str(t) for t in _list(e.get("technologies"))}]
        by_node = [e for e in ecos if e not in by_tech and _nodes(e) & nodes]
        products = [
            p
            for p in cps
            if _nodes(p) & nodes or techs & {str(t) for t in _list(p.get("technologies"))}
        ]
        missing = []
        if not by_tech and not by_node:
            missing.append("缺生態系")
        if not products:
            missing.append("缺客戶產品")
        status = _status(flags, rows, missing)
        rows.append([_ref(trend), _prio(trend), len(by_tech), len(by_node), len(products), status])
    return _section(
        "20",
        "趨勢 × 生態系 × 客戶產品 三方掛勾檢查",
        ["趨勢", "優先度", "生態系（技術掛勾）", "生態系（節點掛勾）", "客戶產品數", "檢查"],
        rows,
        flags=flags,
        note="生態系由技術相同（強）或節點相同（弱）推得；任一欄為 0 代表那條鏈斷了。",
    )


def win_loss(c: dict[str, list[Card]], d: str) -> dict[str, Any]:
    records = _of(c, "WinLoss", d)
    rows: list[list[Any]] = []
    for name in sorted({str(x) for w in records for x in _list(w.get("competitors"))}):
        mine = [w for w in records if name in {str(x) for x in _list(w.get("competitors"))}]
        lost = [w for w in mine if w.get("outcome") == "lost"]
        reasons: dict[str, int] = {}
        for w in lost:
            if w.get("primary_reason"):
                reasons[str(w["primary_reason"])] = reasons.get(str(w["primary_reason"]), 0) + 1
        top = max(reasons.items(), key=lambda kv: (kv[1], kv[0])) if reasons else None
        won = sum(1 for w in mine if w.get("outcome") == "won")
        rows.append([name, len(mine), won, len(lost), f"{top[0]} ×{top[1]}" if top else "-"])
    reviewed = {str(w.get("opportunity")) for w in records if w.get("opportunity")}
    flags: list[dict[str, Any]] = []
    for opp in _of(c, "Opportunity", d):
        if opp.get("deal_stage") in ("won", "lost") and opp["_key"] not in reviewed:
            flags.append({"row": len(rows), "level": "warn", "text": "尚未復盤"})
            rows.append([_ref(opp), "-", "", "", f"{opp.get('deal_stage')}：⚠ 尚未復盤"])
    return _section(
        "21",
        "Win-Loss 原因統計（依對手）",
        ["對手 / 已結案商機", "案例數", "贏", "輸", "輸單最常見原因"],
        rows,
        flags=flags,
        note="結果與主因來自 WinLoss 卡；已結案但沒有 WinLoss 卡的商機列在最後（尚未復盤）。",
    )


def roadmap_gaps(c: dict[str, list[Card]], d: str) -> dict[str, Any]:
    open_requests = [
        r
        for r in _of(c, "RoadmapRequest", d)
        if r.get("request_status") not in ("shipped", "declined")
    ]

    def score(r: Card) -> int:
        return int(r.get("impact") or 0) * int(r.get("customer_count") or 1)

    rows: list[list[Any]] = []
    flags: list[dict[str, Any]] = []
    for r in sorted(open_requests, key=lambda r: (-score(r), r["_name"])):
        evidence = len(_list(r.get("source_win_loss"))) + len(_list(r.get("source_opportunities")))
        status = _status(flags, rows, [] if evidence else ["無證據來源"])
        rows.append(
            [
                _ref(r),
                r.get("gap_type") or "-",
                r.get("impact") or "-",
                r.get("customer_count") or "-",
                score(r),
                r.get("request_status") or "-",
                len(_list(r.get("source_win_loss"))),
                _join(r.get("our_solutions")),
                status,
            ]
        )
    return _section(
        "22",
        "Roadmap Request 缺口排行",
        ["需求", "缺口類型", "影響", "客戶數", "分數", "狀態", "來源案例", "方案", "檢查"],
        rows,
        flags=flags,
        note="排序：影響程度 × 受影響客戶數；沒有 Win-Loss 或商機來源的需求標「無證據來源」。",
    )


def enablement(c: dict[str, list[Card]], d: str) -> dict[str, Any]:
    cards = _of(c, "Battlecard", d)
    pitches, demos = _of(c, "Pitch", d), _of(c, "DemoScript", d)
    rows: list[list[Any]] = []
    flags: list[dict[str, Any]] = []
    for comp in sorted(_of(c, "Competitor", d), key=lambda x: x["_name"]):
        mine = [b for b in cards if b.get("competitor") == comp["_key"]]
        reviewed = sum(1 for b in mine if b.get("content_status") not in (None, "draft"))
        status = _status(flags, rows, [] if mine else ["無 Battlecard"])
        rows.append([_ref(comp), "對手", len(mine), reviewed, status])
    for sol in sorted(_of(c, "TestSolution", d), key=lambda x: x["_name"]):
        if sol.get("vendor"):
            continue

        def using(items: list[Card], s: Card = sol) -> int:
            return sum(
                1 for x in items if s["_key"] in {str(v) for v in _list(x.get("our_solutions"))}
            )

        missing = [
            label
            for label, count in (
                ("Pitch", using(pitches)),
                ("Demo", using(demos)),
                ("Battlecard", using(cards)),
            )
            if not count
        ]
        status = _status(flags, rows, [f"缺 {'、'.join(missing)}"] if missing else [])
        rows.append([_ref(sol), "我方方案", using(pitches), using(demos), status])
    return _section(
        "23",
        "Sales Enablement 覆蓋（對手 Battlecard / 我方方案 Pitch 與 Demo）",
        ["對象", "類別", "Battlecard 數 / Pitch", "已審閱 / Demo 腳本", "檢查"],
        rows,
        flags=flags,
    )


def customer_contact(c: dict[str, list[Card]], d: str, today: date | None = None) -> dict[str, Any]:
    now = today or _today()
    limit = (now - timedelta(days=VISIT_DAYS)).isoformat()
    visits = _of(c, "VisitLog", d)
    rows: list[list[Any]] = []
    flags: list[dict[str, Any]] = []
    for opp in sorted(_of(c, "Opportunity", d), key=lambda x: x["_name"]):
        if opp.get("deal_stage") in ("won", "lost"):
            continue
        mine = sorted(
            (_day(v.get("date")) for v in visits if v.get("opportunity") == opp["_key"]),
            reverse=True,
        )
        last = mine[0] if mine else ""
        problem = "無拜訪紀錄" if not last else ("超過 60 天" if last < limit else "")
        status = _status(flags, rows, [problem] if problem else [])
        rows.append([_ref(opp), opp.get("deal_stage") or "-", len(mine), last or "-", status])
    for visit in visits:
        due = _day(visit.get("follow_up_date"))
        if due and due < now.isoformat():
            flags.append({"row": len(rows), "level": "warn", "text": "跟進逾期"})
            rows.append([_ref(visit), visit.get("account") or "-", "", due, "⚠ 跟進逾期"])
    return _section(
        "24",
        "客戶接觸：進行中商機的最近拜訪與逾期跟進",
        ["商機 / 拜訪", "階段 / 客戶", "拜訪次數", "最近拜訪 / 跟進日", "檢查"],
        rows,
        flags=flags,
        note=f"進行中商機超過 {VISIT_DAYS} 天沒有拜訪紀錄標警示；跟進日已過的拜訪也列出。",
    )


def _supply(c: dict[str, list[Card]], d: str, product: Card, grades: tuple[str, ...]) -> list[str]:
    found: list[str] = []
    for link in _of(c, "SupplyLink", d):
        if link.get("evidence_grade") not in grades:
            continue
        if product["_key"] in {str(x) for x in _list(link.get("customer_products"))}:
            supplier = str(link.get("supplier") or "")
            if supplier and supplier not in found:
                found.append(supplier)
    return found


def supply_evidence(c: dict[str, list[Card]], d: str) -> dict[str, Any]:
    trends = _of(c, "Trend", d)
    links = _of(c, "SupplyLink", d)
    rows: list[list[Any]] = []
    flags: list[dict[str, Any]] = []
    products = sorted(_of(c, "CustomerProduct", d), key=lambda p: _day(p.get("launch_date")) or "~")
    for product in products:
        nodes, techs = _nodes(product), {str(t) for t in _list(product.get("technologies"))}
        confirmed = _supply(c, d, product, CONFIRMED)
        pending = [s for s in _supply(c, d, product, ("C", "D")) if s not in confirmed]
        carded = {str(x.get("supplier")) for x in links if product["_key"] in {
            str(p) for p in _list(x.get("customer_products"))}}  # fmt: skip
        no_card = [e for e in (str(x) for x in _list(product.get("ecosystem"))) if e not in carded]
        inferred = [
            t
            for t in trends
            if techs & {str(x) for x in _list(t.get("related_tech"))}
            or nodes & {str(x) for x in _list(t.get("affected_nodes"))}
        ]
        via_supplier = [
            t
            for t in trends
            if set(confirmed) & {str(x) for x in _list(t.get("related_ecosystem"))}
        ]
        both = [t for t in inferred if t in via_supplier]
        every = sorted(
            {t["_key"]: t for t in [*inferred, *via_supplier]}.values(), key=lambda t: -_prio(t)
        )
        problems = []
        if not confirmed:
            problems.append("無 A/B 供應商")
        if not every:
            problems.append("無趨勢")
        if confirmed and not via_supplier:
            problems.append("供應商未連趨勢")
        if no_card:
            problems.append(f"ecosystem 欄 {len(no_card)} 筆無證據卡")
        status = _status(flags, rows, problems)
        rows.append(
            [
                _ref(product),
                _day(product.get("launch_date")) or product.get("launch_window") or "-",
                "、".join(confirmed) or "-",
                "、".join(pending) or "-",
                len(inferred),
                len(via_supplier),
                len(both),
                _ref(every[0]) if every else "-",
                status,
            ]
        )
    return _section(
        "25",
        "客戶產品 × 生態系 × 趨勢（以供貨證據為準）",
        [
            "客戶產品",
            "上市",
            "已確認供應商（A/B）",
            "待確認（C/D）",
            "趨勢（推算）",
            "趨勢（供應商連結）",
            "兩者皆中",
            "最高優先趨勢",
            "檢查",
        ],
        rows,
        flags=flags,
        note="生態系只計 SupplyLink 證據 A/B 的供應商；C/D 列為待確認。兩條路都命中是最強掛勾。",
    )


def _months_to(day: str, today: date) -> float | None:
    try:
        when = date.fromisoformat(day)
    except ValueError:
        return None
    return (when - today).days / 30.44


def timing_gaps(c: dict[str, list[Card]], d: str, today: date | None = None) -> dict[str, Any]:
    now = today or _today()
    trends = [t for t in _of(c, "Trend", d) if t.get("stage") != "fading"]
    mine = [s for s in _of(c, "TestSolution", d) if not s.get("vendor")]
    rows: list[list[Any]] = []
    flags: list[dict[str, Any]] = []
    products = sorted(_of(c, "CustomerProduct", d), key=lambda p: _day(p.get("launch_date")) or "~")
    for product in products:
        launch = _day(product.get("launch_date"))
        months = _months_to(launch, now) if launch else None
        if months is None:
            flags.append({"row": len(rows), "level": "warn", "text": "缺 launch_date"})
            rows.append([_ref(product), "-", "-", "-", "-", "-", "⚠ 缺 launch_date"])
            continue
        nodes, techs = _nodes(product), {str(t) for t in _list(product.get("technologies"))}
        suppliers = set(_supply(c, d, product, CONFIRMED))
        hit = [
            t
            for t in trends
            if techs & {str(x) for x in _list(t.get("related_tech"))}
            or nodes & {str(x) for x in _list(t.get("affected_nodes"))}
            or suppliers & {str(x) for x in _list(t.get("related_ecosystem"))}
        ]
        early = [
            t
            for t in hit
            if t.get("time_to_demand") in DEMAND_START
            and DEMAND_START[str(t["time_to_demand"])] <= months
        ]
        apps = {str(a) for a in _list(product.get("inferred_applications"))}
        sols = [s for s in mine if apps & {str(a) for a in _list(s.get("applications"))}]
        available = sum(1 for s in sols if s.get("status") == "available")
        planning = sum(1 for s in sols if s.get("status") == "planning")
        if not apps:
            status, level = "⚠ 缺 inferred_applications", "warn"
        elif not early:
            status, level = "OK（無早於上市的趨勢需求）", ""
        elif available:
            status, level = "OK", ""
        elif planning:
            status, level = "🟡 方案規劃中", "warn"
        else:
            status, level = "🔴 趨勢需求已到、我方無方案", "red"
        if level:
            flags.append({"row": len(rows), "level": level, "text": status})
        rows.append(
            [
                _ref(product),
                launch,
                round(months, 1),
                product.get("test_stage_now") or "-",
                "、".join(t["_name"] for t in early) or "-",
                f"{available} / {planning}",
                status,
            ]
        )
    return _section(
        "26",
        "時程缺口：趨勢需求早於產品上市、但我方方案尚未 available",
        [
            "客戶產品",
            "上市日",
            "倒數（月）",
            "目前階段",
            "上市時已有需求的趨勢",
            "我方方案（available / planning）",
            "檢查",
        ],
        rows,
        flags=flags,
        note="time_to_demand 的起點（0-6m→0、6-18m→6、18-36m→18、36m+→36 個月）≤ 上市倒數月數，"
        "視為上市時需求已存在。",
    )


def supply_grades(c: dict[str, list[Card]], d: str) -> dict[str, Any]:
    links = _of(c, "SupplyLink", d)
    rows: list[list[Any]] = []
    for grade in ("A", "B", "C", "D"):
        mine = [x for x in links if (x.get("evidence_grade") or "D") == grade]
        rows.append(
            [
                GRADE_LABELS[grade],
                *(sum(1 for x in mine if x.get("supply_stage") == s) for s in SUPPLY_STAGES),
                sum(1 for x in mine if not x.get("supply_stage")),
                len(mine),
            ]
        )
    flags: list[dict[str, Any]] = []
    for link in links:
        if link.get("evidence_grade") in CONFIRMED and not (
            link.get("source") and link.get("source_date")
        ):
            lacking = [k for k in ("source", "source_date") if not link.get(k)]
            flags.append({"row": len(rows), "level": "warn", "text": "缺 " + "、".join(lacking)})
            rows.append(
                [_ref(link), link["evidence_grade"], *([""] * 5), "⚠ 缺 " + "、".join(lacking)]
            )
    return _section(
        "27",
        "供貨證據等級分布（SupplyLink）",
        ["等級", *SUPPLY_STAGES, "未標階段", "合計"],
        rows,
        flags=flags,
        note="A/B 級缺 source 或 source_date 的列在表後；D 級不可當成已確認的供貨線。",
    )


def revenue_layers(c: dict[str, list[Card]], d: str) -> dict[str, Any]:
    facts = _of(c, "RevenueFact", d)
    by_company: dict[str, list[Card]] = {}
    for fact in facts:
        by_company.setdefault(str(fact.get("company") or "-"), []).append(fact)
    rows: list[list[Any]] = []
    flags: list[dict[str, Any]] = []
    for company in sorted(by_company):
        mine = by_company[company]

        def layer(name: str, m: list[Card] = mine) -> int:
            return sum(1 for f in m if f.get("rev_layer") == name)

        def basis(name: str, m: list[Card] = mine) -> int:
            return sum(1 for f in m if (f.get("basis") or "estimated") == name)

        missing = [
            label
            for label, name in (
                ("公司層", "company"),
                ("區段層", "segment"),
                ("客戶層未揭露", "customer"),
            )
            if not layer(name)
        ]
        status = _status(flags, rows, [f"缺 {'、'.join(missing)}"] if missing else [])
        periods = "、".join(sorted({str(f.get("period")) for f in mine if f.get("period")}))
        rows.append(
            [
                company,
                periods,
                layer("company"),
                layer("segment"),
                layer("customer"),
                basis("reported"),
                basis("media"),
                basis("estimated"),
                basis("target"),
                status,
            ]
        )
    for account in sorted(_of(c, "Account", d), key=lambda a: a["_name"]):
        if account["_key"] not in by_company:
            flags.append({"row": len(rows), "level": "warn", "text": "無任何 RevenueFact"})
            rows.append([_ref(account), "", "", "", "", "", "", "", "", "⚠ 無任何 RevenueFact"])
    return _section(
        "28",
        "收入事實三層完整度（RevenueFact）",
        [
            "公司",
            "期間",
            "公司層",
            "區段層",
            "客戶層",
            "reported",
            "media",
            "estimated",
            "target",
            "檢查",
        ],
        rows,
        flags=flags,
        note="口徑：reported 財報、media 媒體、estimated 推算、target 目標（target 不可當實績）。",
    )


def _is_mine(name: str) -> bool:
    return any(word in name.lower() for word in MINE_RE)


def chain_integrity(c: dict[str, list[Card]], d: str) -> dict[str, Any]:
    competitors = {x["_key"]: x for x in c.get("Competitor", [])}
    solutions = {x["_key"]: x for x in c.get("TestSolution", [])}
    rows: list[list[Any]] = []
    flags: list[dict[str, Any]] = []
    for sol in sorted(_of(c, "TestSolution", d), key=lambda x: x["_name"]):
        vendor = str(sol.get("vendor") or "")
        if not vendor:
            continue
        found = competitors.get(vendor)
        problem = (
            "我方方案請清空 vendor"
            if _is_mine(vendor)
            else "vendor 不是 Competitor 卡"
            if found is None
            else f"Competitor 卡的 domain 未含 {d}"
            if not _in(found, d)
            else ""
        )
        status = _status(flags, rows, [problem] if problem else [])
        rows.append([_ref(sol), "對手方案", vendor, "", status])
    for opp in sorted(_of(c, "Opportunity", d), key=lambda x: x["_name"]):
        ours = [str(x) for x in _list(opp.get("our_solutions"))]
        apps = [str(x) for x in _list(opp.get("applications"))]
        rivals = [str(x) for x in _list(opp.get("competitors"))]
        problems = []
        if not ours:
            problems.append("無我方方案")
        wrong = [n for n in ours if n in solutions and solutions[n].get("vendor")]
        ghost = [n for n in ours if n not in solutions]
        if wrong:
            problems.append("our_solutions 連到對手方案：" + "、".join(wrong))
        if ghost:
            problems.append("方案卡不存在：" + "、".join(ghost))
        if not apps:
            problems.append("無 Application")
        covered = {
            str(a)
            for n in ours
            if n in solutions and not solutions[n].get("vendor")
            for a in _list(solutions[n].get("applications"))
        }
        uncovered = [a for a in apps if a not in covered]
        if ours and apps and uncovered and not wrong:
            problems.append("我方方案未涵蓋：" + "、".join(uncovered))
        bad = [n for n in rivals if n not in competitors or _is_mine(n)]
        if bad:
            problems.append("competitors 不是 Competitor 卡：" + "、".join(bad))
        status = _status(flags, rows, problems)
        if wrong:
            flags[-1]["level"] = "red"
        rows.append([_ref(opp), opp.get("deal_stage") or "-", "、".join(ours) or "-",
                     "、".join(rivals) or "-", status])  # fmt: skip
    return _section(
        "29",
        "鏈路完整性：Application → 我方方案 → Opportunity（含競品連結）",
        ["方案 / 商機", "類別 / 階段", "vendor / 我方方案", "對手", "檢查"],
        rows,
        flags=flags,
        note="我方 = vendor 空白的 TestSolution；對手方案的 vendor 要連到 Competitor 卡。",
    )


def same_names(c: dict[str, list[Card]], d: str) -> dict[str, Any]:
    where: dict[str, list[str]] = {}
    for type_name, cards in c.items():
        for card in cards:
            where.setdefault(card["_name"].lower(), []).append(type_name)
    rows: list[list[Any]] = []
    flags: list[dict[str, Any]] = []
    for name, types in sorted(where.items()):
        if len(types) > 1:
            flags.append({"row": len(rows), "level": "warn", "text": "同名卡"})
            rows.append([name, "、".join(sorted(types)), "⚠ 同名卡，請合併或改名"])
    return _section(
        "30",
        "同名卡衝突（同一個名字出現在不同類型）",
        ["名稱", "類型", "檢查"],
        rows,
        flags=flags,
        note="典型情況：同一家公司同時建了 Account 與 Ecosystem，"
        "或 Keysight 同時是 Competitor 與 Ecosystem。",
    )


def pending_links(
    c: dict[str, list[Card]], d: str, link_fields: dict[str, dict[str, list[str]]]
) -> dict[str, Any]:
    known = {card["_key"].lower() for cards in c.values() for card in cards} | {
        card["_name"].lower() for cards in c.values() for card in cards
    }
    pending: dict[str, dict[str, Any]] = {}
    for type_name, cards in c.items():
        for card in cards:
            for field_name, targets in link_fields.get(type_name, {}).items():
                for target in _list(card.get(field_name)):
                    name = str(target)
                    if not name or name.lower() in known:
                        continue
                    entry = pending.setdefault(name, {"refs": [], "types": {}})
                    if card["_name"] not in entry["refs"]:
                        entry["refs"].append(card["_name"])
                    hint = " / ".join(targets) or "?"
                    entry["types"][hint] = entry["types"].get(hint, 0) + 1
    rows: list[list[Any]] = []
    for name, entry in sorted(pending.items(), key=lambda kv: (-len(kv[1]["refs"]), kv[0]))[:40]:
        hint = max(entry["types"].items(), key=lambda kv: kv[1])[0]
        rows.append([name, len(entry["refs"]), hint, "、".join(entry["refs"][:3])])
    return _section(
        "31",
        "待補的連結目標（後補清單）",
        ["待補目標", "被引用卡數", "建議卡種", "引用來源（前 3）"],
        rows,
        note="卡片已連到、但對應的卡還沒建立的名稱；建立同名卡後連結自動接上。同一家公司有多種叫法時，"
        "在「領域設定」的 name_aliases 統一。",
    )


